from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from config.database import engine

app = FastAPI(
    title="Customer Management API",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/")
def root():
    return {"status": "ok"}

@app.get("/health")
def health():
    return {"message": "healthy"}